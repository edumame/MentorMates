-- M1a: additive storage only. Does not hide/remove legacy fields or change project RLS.
-- Do not apply until the staging rehearsal in project-identity-rollout/README.md.
BEGIN;
SET LOCAL lock_timeout = '2s';
SET LOCAL statement_timeout = '30s';
DO $owner$ BEGIN
  IF current_user <> 'postgres' THEN RAISE EXCEPTION 'Apply identity migrations as postgres'; END IF;
END; $owner$;

CREATE SCHEMA project_identity_private AUTHORIZATION postgres;
REVOKE ALL ON SCHEMA project_identity_private FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA project_identity_private
  REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA project_identity_private
  REVOKE ALL ON SEQUENCES FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA project_identity_private
  REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC, anon, authenticated;

CREATE TABLE public.project_members (
  project_id uuid NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  role text NOT NULL CHECK (role IN ('lead', 'member')),
  joined_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (project_id, user_id)
);
CREATE INDEX project_members_user_project_idx
  ON public.project_members (user_id, project_id);
CREATE UNIQUE INDEX project_members_one_lead_idx
  ON public.project_members (project_id) WHERE role = 'lead';
ALTER TABLE public.project_members ENABLE ROW LEVEL SECURITY;
-- Service code reads identities; writes go through the narrowly granted functions.
REVOKE ALL ON public.project_members FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT ON public.project_members TO service_role;
COMMENT ON TABLE public.project_members IS
  'Project identity by auth UUID. Not authoritative until private state.source = members.';

CREATE TABLE project_identity_private.rollout (
  singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
  phase text NOT NULL DEFAULT 'expanded'
    CHECK (phase IN ('expanded', 'privacy', 'members', 'contracted')),
  compatible_build text,
  backfill_paused boolean NOT NULL DEFAULT true,
  backfill_after uuid,
  backfill_finished_at timestamptz,
  -- One project per RPC transaction; the external runner controls pacing.
  max_batch_size integer NOT NULL DEFAULT 1 CHECK (max_batch_size = 1),
  updated_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO project_identity_private.rollout (singleton) VALUES (true);

CREATE TABLE project_identity_private.project_identity_state (
  project_id uuid PRIMARY KEY REFERENCES public.projects(id) ON DELETE CASCADE,
  source text NOT NULL DEFAULT 'legacy' CHECK (source IN ('legacy', 'members')),
  revision bigint NOT NULL DEFAULT 0 CHECK (revision >= 0),
  lead_unclaimed boolean NOT NULL DEFAULT true,
  initialized_at timestamptz NOT NULL DEFAULT now(),
  verified_at timestamptz,
  migrated_at timestamptz,
  CHECK (source <> 'members' OR migrated_at IS NOT NULL)
);
CREATE INDEX project_identity_state_pending_idx
  ON project_identity_private.project_identity_state (project_id) WHERE source = 'legacy';

CREATE TABLE project_identity_private.project_identity_reconciliation (
  project_id uuid NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  legacy_role text NOT NULL CHECK (legacy_role IN ('lead', 'member')),
  normalized_email text NOT NULL,
  original_emails text[] NOT NULL,
  resolved_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  reason text NOT NULL CHECK (reason IN (
    'matched', 'empty', 'invalid', 'missing_account', 'unverified',
    'ambiguous_account', 'profile_conflict', 'duplicate_user'
  )),
  first_seen_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (project_id, legacy_role, normalized_email)
);
CREATE INDEX project_identity_reconciliation_pending_idx
  ON project_identity_private.project_identity_reconciliation (project_id)
  WHERE reason <> 'matched';

CREATE TABLE project_identity_private.project_invitations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  project_id uuid NOT NULL REFERENCES public.projects(id) ON DELETE CASCADE,
  -- Lowercase hex SHA-256 of a random token generated by the server. No JWT emails.
  token_hash text NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  inviter_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  recipient_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  recipient_email text,
  target_kind text NOT NULL CHECK (target_kind IN ('user', 'email', 'share')),
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  accepted_at timestamptz,
  accepted_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  CHECK (expires_at > created_at),
  CHECK (recipient_email IS NULL OR
    (recipient_email = lower(btrim(recipient_email)) AND recipient_email <> '')),
  -- target_kind prevents a deleted recipient UUID from becoming a general invite.
  CHECK (
    (target_kind = 'share' AND recipient_user_id IS NULL AND recipient_email IS NULL)
    OR (target_kind = 'email' AND recipient_email IS NOT NULL)
    OR target_kind = 'user'
  )
);
CREATE INDEX project_invitations_project_idx
  ON project_identity_private.project_invitations (project_id);
CREATE INDEX project_invitations_recipient_idx
  ON project_identity_private.project_invitations (recipient_user_id)
  WHERE recipient_user_id IS NOT NULL;

ALTER TABLE project_identity_private.rollout ENABLE ROW LEVEL SECURITY;
ALTER TABLE project_identity_private.project_identity_state ENABLE ROW LEVEL SECURITY;
ALTER TABLE project_identity_private.project_identity_reconciliation ENABLE ROW LEVEL SECURITY;
ALTER TABLE project_identity_private.project_invitations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA project_identity_private
  FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA project_identity_private
  FROM PUBLIC, anon, authenticated, service_role;
-- Kept out of the Data API; service-role access is through explicit public RPCs.
REVOKE ALL ON SCHEMA project_identity_private FROM service_role;

COMMIT;
